// scripts/fetch-k8s-icons.mjs — one-off: downloads the official Kubernetes resource icons and
// strips Inkscape metadata; the heptagon fill becomes currentColor so CSS drives the family color.
// Source: https://github.com/kubernetes/community/tree/master/icons (CC BY 4.0). Run: node scripts/fetch-k8s-icons.mjs
import { mkdir, writeFile } from 'node:fs/promises';
import path from 'node:path';

const BASE = 'https://raw.githubusercontent.com/kubernetes/community/master/icons/svg/resources/unlabeled/';
const NAMES = ['deploy', 'sts', 'ds', 'job', 'cronjob', 'svc', 'ing', 'cm', 'secret', 'pvc', 'sa', 'role', 'rb', 'netpol', 'hpa', 'crd', 'pod'];
const out = path.resolve('src/canvas/icons');
await mkdir(out, { recursive: true });

const must = (m, what) => { if (!m) throw new Error(`unexpected SVG layout: ${what}`); return m; };
const clean = (name, svg) => {
  let s = svg.replace(/<\?xml[\s\S]*?\?>/, '').replace(/<!--[\s\S]*?-->/g, '')
    .replace(/<metadata[\s\S]*?<\/metadata>/g, '').replace(/<sodipodi:namedview[\s\S]*?\/>/g, '')
    .replace(/<defs[^>]*\/>/g, '').replace(/<defs[\s\S]*?<\/defs>/g, '');
  const vb = must(s.match(/viewBox="([^"]+)"/), `${name}: viewBox`)[1];
  let inner = must(s.match(/<svg[^>]*>([\s\S]*)<\/svg>/), `${name}: svg root`)[1]
    .replace(/\s(inkscape|sodipodi):[\w-]+="[^"]*"/g, '').replace(/\sid="[^"]*"/g, '')
    // defs are gone, so any reference into them would make the element not render at all
    .replace(/\s(clip-path|mask|filter)="[^"]*"/g, '')
    .replace(/#326ce5/gi, 'currentColor')
    .replace(/\s+/g, ' ').trim();
  return { vb, inner };
};

let base = null;
const boxes = new Set();
for (const n of NAMES) {
  const res = await fetch(BASE + n + '.svg');
  if (!res.ok) throw new Error(`${n}: HTTP ${res.status}`);
  const { vb, inner } = clean(n, await res.text());
  boxes.add(vb);
  if (n === 'deploy') base = { vb, inner };
  await writeFile(path.join(out, `${n}.svg`), `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${vb}">${inner}</svg>\n`);
  console.log('ok', n);
}
if (boxes.size !== 1) throw new Error(`icons do not share one viewBox: ${[...boxes].join(' | ')}`);
// KindIcon re-wraps each file's inner markup in one shared viewBox; emit it so the code and the test never drift from the files.
await writeFile(path.join(out, 'viewbox.ts'), `// generated by scripts/fetch-k8s-icons.mjs\nexport const ICON_VIEWBOX = '${base.vb}';\n`);
// Release: the heptagon (first two paths of deploy, inside their transform groups) plus a ship's wheel.
const wrap = must(base.inner.match(/^(<g[^>]*>\s*<g[^>]*>)/), 'deploy: two wrapping <g>')[1];
const paths = must(base.inner.match(/<path [\s\S]*?\/>/g), 'deploy: paths').slice(0, 2).join('');
const wheel = '<g fill="none" stroke="#ffffff" stroke-width="0.85" stroke-linecap="round"><circle cx="9.02" cy="9.25" r="1.05"/><circle cx="9.02" cy="9.25" r="3.3"/><path d="M9.02 4.6v3.6M9.02 10.3v3.55M4.37 9.25h3.6M10.07 9.25h3.6M5.73 5.96l2.55 2.55M9.76 9.99l2.55 2.55M5.73 12.54l2.55-2.55M9.76 8.51l2.55-2.55"/></g>';
await writeFile(path.join(out, 'helm.svg'), `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${base.vb}">${wrap}${paths}</g></g>${wheel}</svg>\n`);
console.log('ok helm');
